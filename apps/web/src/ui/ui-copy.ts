export function copyForLocale(locale: AppLocale = "en"): UiCopy {
  return { en, de, es, fr }[locale];
}
export function browserLocale(): AppLocale {
  if (typeof document === "undefined") return "en";
  const value = document.cookie
    .split("; ")
    .find((entry) => entry.startsWith(`${LOCALE_COOKIE}=`))
    ?.split("=")[1];
  return isAppLocale(value) ? value : "en";
}
export function localizedAxis(copy: UiCopy, id: string) {
  return copy.appearance.axes[id as keyof typeof copy.appearance.axes] ?? id;
}

